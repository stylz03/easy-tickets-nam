-- Only catalogue data and remaining counts are returned, never buyer data.
create function public.website_catalogue() returns table(payload jsonb)
language sql stable security definer set search_path='' as $$
 select jsonb_set(e.payload,'{tiers}',(
   select jsonb_agg(t || jsonb_build_object('available', greatest(0,(t->>'capacity')::integer - coalesce((
     select sum((i->>'qty')::integer)::integer
     from public.orders o cross join lateral jsonb_array_elements(o.items) i
     where o.event_id=e.id and o.status in ('pending','paid') and i->>'tier'=t->>'id'
   ),0))) order by ordinal)
   from jsonb_array_elements(e.payload->'tiers') with ordinality as types(t,ordinal)
 ))
 from public.website_events e where e.published and e.starts_at > now() order by e.starts_at;
$$;
revoke execute on function public.website_catalogue() from public,anon,authenticated;
grant execute on function public.website_catalogue() to service_role;

