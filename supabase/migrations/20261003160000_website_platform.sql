-- Concurrent scanner requests can mark the same ticket used only once.
create function public.check_in_website_ticket(p_ticket_id uuid,p_secret text,p_event_id integer) returns jsonb
language plpgsql security definer set search_path='' as $$
declare t public.website_tickets;
begin
 if not exists(select 1 from public.website_event_staff where event_id=p_event_id and user_id=auth.uid()) then raise exception 'Staff assignment required'; end if;
 select * into t from public.website_tickets where id=p_ticket_id and event_id=p_event_id and secret=p_secret for update;
 if t.id is null then return jsonb_build_object('ok',false,'error','Ticket not valid for this event.'); end if;
 if t.status='used' then return jsonb_build_object('ok',false,'error','This ticket has already been used.'); end if;
 if t.status<>'valid' or not exists(select 1 from public.orders where id=t.order_id and status='paid') then return jsonb_build_object('ok',false,'error','This ticket is not valid.'); end if;
 update public.website_tickets set status='used',checked_in_at=now(),checked_in_by=auth.uid() where id=t.id and status='valid';
 return jsonb_build_object('ok',true,'holder',t.holder_name,'tier',t.tier_name);
end $$;
revoke execute on function public.check_in_website_ticket(uuid,text,integer) from public,anon;
grant execute on function public.check_in_website_ticket(uuid,text,integer) to authenticated;

